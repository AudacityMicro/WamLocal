function fixture(machine: "desktop" | "pro" = "pro") {
  const j = newJob(machine);
  j.materials[0] = {
    ...j.materials[0],
    feed: 120,
    pierce: 2.5,
    kerf: 0.8,
    lead: 2,
    tabCount: 0,
    tabWidth: 2,
    requiresVerification: false,
  };
  j.parts = [
    {
      ...makePart("plate", [
        rectangle(40, 30),
        {
          ...circle(5),
          hole: true,
          points: circle(5).points.map((p) => ({ x: p.x + 10, y: p.y + 10 })),
        },
      ]),
      materialId: j.materials[0].id,
      quantity: 1,
    },
  ];
  j.sheets[0].placements = [
    {
      id: "placement",
      partId: j.parts[0].id,
      x: 20,
      y: 20,
      scale: 1,
      rotation: 0,
    },
  ];
  return j;
}
/** Independent controller-state replay: no G0 with power, no unpowered G1. */
function replay(source: string) {
  let water = false,
    abrasive = false,
    initialized = false,
    finished = false,
    absolute = false,
    mm = false,
    feed = 0;
  const controls: string[] = [];
  for (const raw of source.split(/\r?\n/)) {
    const line = raw.split(";")[0].trim();
    if (!line) continue;
    const code = line.split(" ")[0];
    expect(finished).toBe(false);
    if (code === "G90") absolute = true;
    else if (code === "G21") mm = true;
    else if (code === "M1403") initialized = true;
    else if (code === "M3") {
      expect(water).toBe(false);
      water = true;
    } else if (code === "M8") {
      expect(water).toBe(true);
      expect(abrasive).toBe(false);
      abrasive = true;
    } else if (code === "M9") abrasive = false;
    else if (code === "M5") {
      expect(abrasive).toBe(false);
      water = false;
    } else if (code === "G0" || code === "G1") {
      expect(initialized && absolute && mm).toBe(true);
      if (code === "G0") expect(water || abrasive).toBe(false);
      else {
        expect(water && abrasive).toBe(true);
        feed = Number(line.match(/F([\d.]+)/)?.[1] ?? feed);
        expect(feed).toBeGreaterThan(0);
      }
    } else if (code === "M1404") {
      expect(water || abrasive).toBe(false);
      finished = true;
    }
    if (/^M/.test(code)) controls.push(code);
  }
  expect(finished).toBe(true);
  return controls;
}
describe("WAZER posting", () => {
  it("sanitizes metadata and rejects a feed that would round to zero", () => {
    const j = fixture();
    j.name = "x\nM3*33";
    j.materials[0].name = "metal\r\nG0 X999*12";
    const source = postJob(j)[0].content;
    expect(source).not.toContain("*");
    expect(replay(source).filter((code) => code === "M3")).toHaveLength(2);
    j.materials[0].feed = 0.000001;
    expect(() => postJob(j)).toThrow(/output precision/);
  });
  it("keeps cut-extents positioning inside the bed and rejects the wrong machine's settings", () => {
    const j = fixture();
    const nc = inspectReferenceNc(postJob(j)[0].content);
    const file = postJob(j)[0].content;
    const top = file.match(/M1405 X([\d.-]+) Y([\d.-]+)/)!;
    const bottom = file.match(/M1406 X([\d.-]+) Y([\d.-]+)/)!;
    expect(Number(top[1])).toBeLessThan(nc.bounds!.x);
    expect(-Number(top[2])).toBeLessThan(nc.bounds!.y);
    expect(Number(bottom[1])).toBeGreaterThan(nc.bounds!.x + nc.bounds!.width);
    expect(-Number(bottom[2])).toBeGreaterThan(
      nc.bounds!.y + nc.bounds!.height,
    );
    j.materials[0].machine = "desktop";
    expect(() => postJob(j)).toThrow(/different machine/);
  });
  it.each(["pro", "desktop"] as const)(
    "posts %s with metric absolute motion, explicit feeds and balanced controls",
    (machine) => {
      const j = fixture(machine),
        file = postJob(j)[0],
        nc = inspectReferenceNc(file.content);
      replay(file.content);
      expect(file.content).toContain("; Generated by Wam Local");
      expect(file.content).not.toContain("Generated on Wam");
      expect(nc.unsupportedCodes).toEqual([]);
      expect(nc.segments).toBe(2);
      expect(file.operations).toBe(2);
      expect(file.filename.length).toBeLessThanOrEqual(13);
      expect(
        nc.moves.filter((m) => !m.rapid).every((m) => m.feed === 120),
      ).toBe(true);
      expect(nc.dwellSeconds).toBe(11);
    },
  );
  it("matches the on/off and final shutdown sequence in the independent WAM capture", () => {
    const reference = readFileSync(
      new URL(
        "../../fixtures/wam-reference/pro/sq-centerline.gcode",
        import.meta.url,
      ),
      "utf8",
    );
    const ours = postJob(fixture())[0].content;
    const stop = (s: string) =>
      s
        .slice(s.lastIndexOf("M9"))
        .split(/\r?\n/)
        .filter((s) => /^M[359]|^G4/.test(s))
        .map((s) => s.replace(/\.$/, ""));
    expect(stop(ours)).toEqual(stop(reference));
    expect(ours).toContain("G90\r\nG21\r\nM1403");
  });
  it("leaves automatic and wrapped manual tab gaps uncut and re-pierces from scrap", () => {
    const j = fixture();
    j.parts[0].contours = [rectangle(40, 30)];
    j.materials[0].tabCount = 2;
    const p = planForPosting(sheetProject(j, j.sheets[0].id));
    expect(p.operations).toHaveLength(2);
    const tabs = p.moves.filter((m) => m.kind === "tab");
    expect(tabs.reduce((n, m) => n + distance(m.from, m.to), 0)).toBeCloseTo(
      4,
      4,
    );
    const file = postJob(j)[0];
    replay(file.content);
    const nc = inspectReferenceNc(file.content);
    expect(nc.segments).toBe(2);
    expect(nc.cutLength).toBeCloseTo(p.cutLength, 2);
    for (const tab of tabs) {
      const midpoint = {
        x: (tab.from.x + tab.to.x) / 2,
        y: (tab.from.y + tab.to.y) / 2,
      };
      expect(
        nc.moves
          .filter((m) => !m.rapid)
          .every(
            (m) =>
              closestOnPath([m.from, m.to], false, midpoint).distance > 0.01,
          ),
      ).toBe(true);
    }
    const c = j.parts[0].contours[0];
    c.tabMode = "manual";
    c.tabs = [
      { position: 0, width: 3 },
      { position: 0.5, width: 4 },
    ];
    const manual = planForPosting(sheetProject(j, j.sheets[0].id));
    expect(manual.operations).toHaveLength(2);
    expect(
      manual.moves
        .filter((m) => m.kind === "tab")
        .reduce((n, m) => n + distance(m.from, m.to), 0),
    ).toBeCloseTo(7, 4);
    replay(postJob(j)[0].content);
  });
  it("maps all nine sheet origins to the same absolute bed coordinates", () => {
    const j = fixture();
    j.sheets[0].wcs = { x: 12, y: 15 };
    const baseline = inspectReferenceNc(postJob(j)[0].content).moves;
    for (const workOrigin of ORIGIN_ANCHORS) {
      j.sheets[0].workOrigin = workOrigin;
      expect(inspectReferenceNc(postJob(j)[0].content).moves).toEqual(baseline);
    }
    expect(
      baseline
        .filter((m) => !m.rapid)
        .every((m) => m.to.x >= 12 && m.to.y >= 15),
    ).toBe(true);
  });
  it("blocks concave stock violations, exclusions and pierce footprints outside the bed", () => {
    const j = fixture();
    j.parts[0].contours = [rectangle(40, 30)];
    j.sheets[0].stock.exclusions = [
      [
        { x: 30, y: 18 },
        { x: 40, y: 18 },
        { x: 40, y: 22 },
        { x: 30, y: 22 },
      ],
    ];
    expect(() => postJob(j)).toThrow(/exclusion/);
    delete j.sheets[0].stock.exclusions;
    j.sheets[0].stock.outline = [
      { x: 0, y: 0 },
      { x: 100, y: 0 },
      { x: 100, y: 100 },
      { x: 60, y: 100 },
      { x: 60, y: 40 },
      { x: 40, y: 40 },
      { x: 40, y: 100 },
      { x: 0, y: 100 },
    ];
    expect(() => postJob(j)).toThrow(/stock outline/);
    delete j.sheets[0].stock.outline;
    j.parts[0].contours[0].startPosition = 0.9;
    j.sheets[0].wcs.x = -17.4;
    expect(() => postJob(j)).toThrow(/footprint exceeds the machine/);
  });
  it("detects a lead crossing even a narrow neighboring part", () => {
    const j = fixture();
    j.parts[0].contours = [{ ...rectangle(40, 30), startPosition: 0.1 }];
    const other = {
      ...j.parts[0],
      id: "narrow",
      name: "narrow",
      contours: [rectangle(0.2, 0.2)],
    };
    j.parts.push(other);
    j.sheets[0].placements.push({
      id: "narrow-copy",
      partId: other.id,
      x: 33.9,
      y: 18.7,
      rotation: 0,
      scale: 1,
    });
    expect(() => postJob(j)).toThrow(/lead crosses retained material/);
  });
  it("rejects bounds, overlap, unverified settings and incomplete post-all without changing the job", () => {
    const j = fixture(),
      before = structuredClone(j);
    postJob(j);
    expect(j).toEqual(before);
    j.materials[0].requiresVerification = true;
    expect(() => postJob(j)).toThrow(/verification/);
    j.materials[0].requiresVerification = false;
    j.sheets[0].placements[0].x = 450;
    expect(() => postJob(j)).toThrow(/outside|cutting area/);
    j.sheets[0].placements[0].x = 20;
    j.parts[0].quantity = 2;
    expect(() => postJob(j)).toThrow(/not all requested/);
    expect(postJob(j, j.sheets[0].id)).toHaveLength(1);
    j.sheets[0].placements.push({
      ...j.sheets[0].placements[0],
      id: "overlap",
    });
    expect(() => postJob(j)).toThrow(/overlap/);
  });
  it("uses per-part feeds and pierce dwell and never cuts tab gaps as G1", () => {
    const j = fixture();
    j.parts[0].contours = [rectangle(20, 15)];
    const m = { ...j.materials[0], id: "custom-feed", feed: 61, pierce: 7 };
    j.materials.push(m);
    j.parts.push({
      ...j.parts[0],
      id: "second",
      name: "second",
      materialId: m.id,
    });
    j.sheets[0].placements.push({
      id: "second-copy",
      partId: "second",
      x: 80,
      y: 50,
      rotation: 17,
      scale: 0.9,
    });
    const source = postJob(j)[0].content;
    replay(source);
    expect(source).toContain("G4 S7");
    expect(source).toContain("F61");
    expect(source).toContain("F120");
    const original = structuredClone(j);
    postJob(j);
    expect(j).toEqual(original);
  });
  it("posts all populated sheets with unique filenames and keeps single-sheet selection isolated", () => {
    const j = fixture();
    j.parts[0].quantity = 2;
    const first = j.sheets[0];
    j.sheets.push({
      ...first,
      id: "second-sheet",
      name: "Sheet 2",
      placements: [{ ...first.placements[0], id: "other-placement" }],
    });
    j.sheets.push({ ...first, id: "empty", placements: [] });
    const files = postJob(jobSchema.parse(j));
    expect(files).toHaveLength(2);
    expect(new Set(files.map((f) => f.filename)).size).toBe(2);
    expect(postJob(j, "second-sheet")[0].sheetId).toBe("second-sheet");
    expect(() => postJob(j, "empty")).toThrow(/no placed parts/);
  });
});
